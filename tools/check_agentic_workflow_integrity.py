"""Fail-closed integrity checks around gh-aw canonical/generated workflow pairs.

The CI wrapper recompiles before invoking this checker. This checker never edits lock files.
"""

from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
WORKFLOWS = ROOT / ".github" / "workflows"


def pairs():
    for source in sorted(WORKFLOWS.glob("*.md")):
        lock = source.with_suffix(".lock.yml")
        if lock.exists():
            yield source, lock


def main():
    found = list(pairs())
    if not found:
        raise SystemExit("no canonical .md -> .lock.yml workflow pairs found")
    status = subprocess.run(
        ["git", "diff", "--exit-code", "--", *[str(lock.relative_to(ROOT)) for _, lock in found]], cwd=ROOT
    ).returncode
    if status:
        raise SystemExit("generated workflow mismatch: run reviewed gh aw compile and commit generated lock output")
    for source, lock in found:
        first = lock.read_text(encoding="utf-8").splitlines()[:4]
        joined = "\n".join(first)
        if "automatically generated by gh-aw" not in joined and "gh-aw-metadata:" not in joined:
            raise SystemExit(f"missing gh-aw generated metadata: {lock.relative_to(ROOT)}")
        print(f"verified pair: {source.relative_to(ROOT)} -> {lock.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
